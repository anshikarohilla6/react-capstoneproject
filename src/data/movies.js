export function getMovieById(movieId) {
  return allMovies.find(function (movie) {
    return String(movie.id) === String(movieId);
  });
}

export function getRelatedMovies(movie, limit = 6) {
  if (!movie) {
    return [];
  }

  return allMovies
    .filter(function (candidate) {
      return String(candidate.id) !== String(movie.id);
    })
    .map(function (candidate) {
      let score = 0;

      if (candidate.genre === movie.genre) {
        score += 4;
      }

      if (candidate.audience === movie.audience) {
        score += 2;
      }

      if (candidate.collection === movie.collection) {
        score += 3;
      }

      if (candidate.tags.some(function (tag) {
        return movie.tags.includes(tag);
      })) {
        score += 2;
      }

      return { candidate, score };
    })
    .sort(function (left, right) {
      return right.score - left.score;
    })
    .slice(0, limit)
    .map(function (entry) {
      return entry.candidate;
    });
}

export function filterMovies(query, movies = allMovies) {
  const normalizedQuery = query.trim().toLowerCase();

  if (!normalizedQuery) {
    return movies;
  }

  return movies.filter(function (movie) {
    const haystack = [movie.title, movie.genre, movie.description, movie.tags.join(' ')].join(' ').toLowerCase();
    return haystack.includes(normalizedQuery);
  });
}